def _is_token(node: Any) -> bool:
    if not isinstance(node, dict):
        return False
    if "$value" in node:
        return True
    return "value" in node and not isinstance(node.get("value"), dict) and (
        "type" in node or set(node) <= {"value", "type", "description", "comment"})


def flatten_dtcg(doc: Any) -> Dict[str, Dict[str, Any]]:
    """Every token in a DTCG (or Tokens Studio) document as
    ``{dotted.path: {"type": ..., "value": resolved}}``. References such as
    ``{color.blue.500}`` are resolved; a reference that cannot be resolved
    keeps its text."""
    raw: Dict[str, Dict[str, Any]] = {}

    def walk(node: Any, path: List[str], inherited: Optional[str]) -> None:
        if not isinstance(node, dict):
            return
        typ = (node.get("$type") or node.get("type")) if _is_token(node) else node.get("$type")
        typ = typ or inherited
        if _is_token(node):
            value = node.get("$value", node.get("value"))
            raw[".".join(path)] = {"type": typ or "", "value": value}
            return
        for key, child in node.items():
            if key.startswith("$"):
                continue
            walk(child, path + [key], typ)

    walk(doc, [], None)

    def resolve(value: Any, depth: int = 0) -> Any:
        if depth > 24:
            return value
        if isinstance(value, str):
            m = re.fullmatch(r"\{([^{}]+)\}", value.strip())
            if m and m.group(1) in raw:
                return resolve(raw[m.group(1)]["value"], depth + 1)
        return value

    out: Dict[str, Dict[str, Any]] = {}
    for key, tok in raw.items():
        value = resolve(tok["value"])
        typ = tok["type"]
        if not typ and normalize_hex(value):
            typ = "color"
        out[key] = {"type": typ, "value": value}
    return out


def _is_design_token(tok: Dict[str, Any]) -> bool:
    """A color or a dimension: what a design token file holds and an API
    key file does not."""
    typ = str(tok.get("type") or "").lower()
    value = tok.get("value")
    if typ in ("color", "dimension", "fontsize", "spacing", "sizing", "borderradius"):
        return True
    if normalize_hex(value):
        return True
    if isinstance(value, dict) and "unit" in value and "value" in value:
        return True
    return isinstance(value, str) and bool(_DIMENSION_RE.match(value.strip()))


def _primary_candidates(names: Iterable[Tuple[str, str]]) -> List[Tuple[str, str, str]]:
    """Every color a name marks as the primary, best named first, as
    (name, hex, the word that marks it): a name that says primary or brand,
    then one that says accent, action, cta or interactive. A leading fill
    word (bg-brand, color-accent) is allowed; a state, a role other than the
    fill, a ramp step or a translucent color is not."""
    ranked: List[Tuple[Tuple[int, int, int, int], str, str, str]] = []
    for order, (name, hx) in enumerate(names):
        segs = _segments(name)
        if not hx or (hx.startswith("#") and len(hx) > 7) or not segs or segs[-1].isdigit():
            continue
        lead = 0
        while lead < len(segs) - 1 and segs[lead] in _FILL_WORDS:
            lead += 1
        words = set(segs[lead:])
        hits = words & _PRIMARY_WORDS
        tier = 0 if hits else 1
        hits = hits or words & _ACTION_WORDS
        if not hits or words & _NOT_PRIMARY:
            continue
        ranked.append(((tier, -len(hits), len(segs), order), name, hx, min(hits)))
    ranked.sort()
    return [(name, hx, word) for _, name, hx, word in ranked]


def _rank_primary(names: Iterable[Tuple[str, str]]) -> Tuple[str, str]:
    found = _primary_candidates(names)
    return (found[0][0], found[0][1]) if found else ("", "")


def _on_color(name: str, named: Dict[str, str]) -> str:
    """The color a token's own text sits in (on-primary, primary-foreground),
    or ""."""
    stem = "-".join(_segments(name))
    for cand in ("on-" + stem, stem + "-foreground", stem + "-fg", stem + "-on",
                 stem + "-text", "text-on-" + stem, stem + "-contrast"):
        hx = named.get(cand, "")
        if len(hx) == 7:
            return hx
    return ""


def _holds_text(name: str, hx: str, named: Dict[str, str], canvas: str) -> str:
    """"" when a primary candidate can carry a button's text, else why not:
    a near-white tint of the page never can, and a fill needs 4.5:1 against
    its own text color, or against the page when it has none."""
    page = canvas or "#FFFFFF"
    if _contrast(hx, page) < _TINT_CONTRAST and _chroma(hx) < _TINT_CHROMA:
        return "%s (%s) is a tint of the page, a hover or surface fill" % (name, hx)
    on = _on_color(name, named)
    if max(_contrast(hx, on) if on else 0.0, _contrast(hx, page)) < _TEXT_MIN_CONTRAST:
        return ("%s (%s) reaches under 4.5:1 against %s, so it cannot carry a button's text"
                % (name, hx, "its text color %s" % on if on else "the page"))
    return ""


def _choose_primary(cands: List[Tuple[str, str, str]], files: List[Path],
                    named: Dict[str, str], canvas: str
                    ) -> Tuple[Tuple[str, str], str, List[Dict[str, Any]]]:
    """(the chosen (name, hex), why, every candidate with its paint count
    when there are several). A name that says primary or brand wins; an
    action color name (accent, action, cta, interactive) is read only when
    none does. A candidate that cannot carry a button's text never wins.
    Of several at one rank, the one the code paints buttons and links with
    most at rest wins; with no such use, the best name. (("", ""), why, ...)
    when no candidate can carry text."""
    refused = {c[0]: _holds_text(c[0], c[1], named, canvas) for c in cands}
    paints = survey.button_paints([c[0] for c in cands], files) if len(cands) > 1 else {}
    listed = [{"token": n, "value": h, "paints": paints[n]} for n, h, _ in cands] \
        if len(cands) > 1 else []
    left = ["%s was left out: %s" % (n, refused[n]) for n, _, _ in cands if refused[n]]
    tail = ("; " + "; ".join(left)) if left else ""
    for tier_words in (_PRIMARY_WORDS, _ACTION_WORDS):
        group = [c for c in cands if c[2] in tier_words]
        ok = [c for c in group if not refused[c[0]]]
        if not ok:
            continue
        name, hx, word = ok[0]
        how = ("its name says %s" % word if word in _PRIMARY_WORDS
               else "its name says %s, an action color, and no color is named primary or "
                    "brand" % word)
        if len(cands) == 1:
            return (name, hx), "%s is the only primary candidate; %s." % (name, how), listed
        if len(ok) > 1:
            best = max(ok, key=lambda c: paints[c[0]])
            if paints[best[0]]:
                n = paints[best[0]]
                others = ", ".join("%s (%d)" % (c[0], paints[c[0]]) for c in ok
                                   if c[0] != best[0])
                return (best[0], best[1]), (
                    "%s is the color the code paints buttons and links with at rest: %d use%s in "
                    "button and link styles and markup, over %s%s." % (
                        best[0], n, "" if n == 1 else "s", others, tail)), listed
            return (name, hx), (
                "%s was chosen because %s; the code paints no button or link with it or with %s "
                "at rest, so confirm it is the action color%s." % (
                    name, how, ", ".join(c[0] for c in ok[1:]), tail)), listed
        rest = [c[0] for c in cands if c[0] != name and not refused[c[0]]]
        over = ("; a name that says primary or brand wins over %s" % ", ".join(rest)
                if rest and word in _PRIMARY_WORDS else "")
        return (name, hx), "%s was chosen because %s%s%s." % (name, how, over, tail), listed
    return ("", ""), ("no primary candidate can carry a button's text: %s; name the action color "
                      "primary, or pass it as the brand primary by hand."
                      % "; ".join(refused[c[0]] for c in cands)), listed


def _luminance(hx: str) -> float:
    def ch(c: int) -> float:
        c = c / 255.0
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = (int(hx[i:i + 2], 16) for i in (1, 3, 5))
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def _contrast(a: str, b: str) -> float:
    la, lb = sorted((_luminance(a), _luminance(b)), reverse=True)
    return (la + 0.05) / (lb + 0.05)


def _chroma(hx: str) -> float:
    r, g, b = (int(hx[i:i + 2], 16) for i in (1, 3, 5))
    hi, lo = max(r, g, b), min(r, g, b)
    return 0.0 if hi == 0 else (hi - lo) / hi


def _rank_text(names: Iterable[Tuple[str, str]], canvas: str = "") -> Tuple[str, str]:
    """The page's text color, read by role name. A text word followed by a
    base word (``text.default``, ``text.primary``, ``fg.base``) ranks first,
    then a name ending in a text word, then any other text name. Status and
    promotion groups (offer, sale, danger, ...) never qualify, and a
    candidate must be near-neutral and reach 4.5:1 on white or the canvas."""
    best: Optional[Tuple[Tuple[int, int, int], str, str]] = None
    grounds = ["#FFFFFF"] + ([canvas] if canvas else [])
    for order, (name, hx) in enumerate(names):
        segs = _segments(name)
        if not hx or len(hx) > 7 or not segs or segs[-1].isdigit():
            continue
        words = set(segs)
        if not words & _TEXT_WORDS or words & _NOT_TEXT:
            continue
        if _chroma(hx) > _TEXT_MAX_CHROMA or max(_contrast(hx, g) for g in grounds) < _TEXT_MIN_CONTRAST:
            continue
        paired = any(a in _TEXT_WORDS and b in _TEXT_BEST for a, b in zip(segs, segs[1:]))
        tier = 0 if paired else (1 if segs[-1] in _TEXT_WORDS else 2)
        score = (tier, len(segs), order)
        if best is None or score < best[0]:
            best = (score, name, hx)
    return (best[1], best[2]) if best else ("", "")


def _canvas(names: Iterable[Tuple[str, str]]) -> str:
    for name, hx in names:
        segs = _segments(name)
        if segs and segs[-1] in ("canvas", "page", "background") and len(hx) == 7:
            return hx
    return ""


def _first_family(value: Any, props: Optional[Dict[str, str]] = None) -> str:
    """The face a font list opens with. A var() member is followed through
    ``props`` or passed over for the named families after it; a list that
    opens with a platform keyword (-apple-system, system-ui) is the
    platform's own face, system-ui."""
    if isinstance(value, list):
        value = ", ".join(str(v) for v in value)
    if not isinstance(value, str):
        return ""
    from engine.io.values_in import split_top  # engine.io imports this package
    for part in (p.strip() for p in split_top(value, ",")):
        if not part:
            continue
        if part.startswith("var("):
            face = _first_family(resolve_css_var(part, props), None) if props else ""
            if face:
                return face
            continue
        name = part.strip('"').strip("'")
        return "system-ui" if name.lower() in _PLATFORM_FAMILIES else name
    return ""


def _fonts_from(names: Iterable[Tuple[str, str]]) -> Dict[str, str]:
    """{display, body} from font tokens by name, and data: a face whose
    name says it sets data, figures or code (mono, numeric, tabular), kept
    as a face of its own and never taken for the body."""
    display = body = data = ""
    for name, family in names:
        if not family:
            continue
        words = set(_segments(name))
        if words & survey.DATA_WORDS:
            data = data or family
        elif not display and words & _DISPLAY_WORDS:
            display = family
        elif not body and (words & _BODY_WORDS or not words & _DISPLAY_WORDS):
            body = family
    if not (display or body):
        display = body = data
    fonts: Dict[str, str] = {}
    if display or body:
        fonts = {"display": display or body, "body": body or display}
    if data and data != fonts.get("body"):
        fonts["data"] = data
    return fonts


# ------------------------------------------------------------------ CSS


def css_custom_properties(text: str) -> Dict[str, str]:
    """Every ``--name: value`` declaration in CSS text, first one wins."""
    text = re.sub(r"/\*.*?\*/", "", text or "", flags=re.S)
    props: Dict[str, str] = {}
    for m in _CUSTOM_PROP_RE.finditer(text):
        props.setdefault(m.group(1), m.group(2).strip())
    return props


def resolve_css_var(value: str, props: Dict[str, str], depth: int = 0) -> str:
    """Follow ``var(--x)`` chains to the final value (fallbacks honored)."""
    if depth > 24 or not isinstance(value, str):
        return value or ""
    # One reader of a var() reference: the importers' css_alias.
    from engine.io.values_in import NotRead, css_alias  # engine.io imports this package
    try:
        ref = css_alias(value)
    except NotRead:
        ref = None
    if ref is None:
        return value.strip()
    name, fallback = "--" + ref[0], ref[1]
    if name in props:
        return resolve_css_var(props[name], props, depth + 1)
    return resolve_css_var(fallback, props, depth + 1) if fallback else ""


# ------------------------------------------------------------------ walk


def _walk(base: Path, depth: int, seen: set, out: List[Path],
          keep: Optional[Any] = None) -> None:
    """Files under ``base``, sorted, to the depth and count caps; with
    ``keep``, only the files it accepts, and only they count to the cap."""
    if depth > _MAX_DEPTH or len(out) >= _MAX_FILES:
        return
    try:
        entries = sorted(base.iterdir())
    except OSError:
        return
    for entry in entries:
        if entry.name in _SKIP_DIRS or entry.is_symlink():
            continue
        if entry.is_dir():
            _walk(entry, depth + 1, seen, out, keep)
        elif entry.is_file() and (keep is None or keep(entry)):
            key = str(entry.resolve())
            if key not in seen:
                seen.add(key)
                out.append(entry)


def _token_doc(path: Path) -> Optional[Any]:
    """The JSON document when it is a design token file: it flattens to at
    least one color or dimension token."""
    text = _read_text(path)
    if '"$value"' not in text and '"value"' not in text:
        return None
    try:
        doc = json.loads(text)
    except ValueError:
        return None
    if not isinstance(doc, dict):
        return None
    return doc if any(_is_design_token(t) for t in flatten_dtcg(doc).values()) else None


def _is_built(path: Path, base: Path) -> bool:
    """Generated output: under a build/dist/out folder, or headed
    "Generated ... Do not edit"."""
    parts = {p.lower() for p in path.relative_to(base).parts[:-1]}
    if parts & _BUILT_DIRS:
        return True
    return bool(_GENERATED_RE.search(_read_text(path, 600)))


def _script_sources(script: Path, base: Path) -> List[Path]:
    """The .json files a build script names that exist inside the project,
    resolved against the script's folder."""
    out: List[Path] = []
    for ref in _SCRIPT_JSON_RE.findall(_read_text(script, 200_000)):
        if re.match(r"^[a-z][a-z0-9+.-]*://", ref, re.I) or "package.json" in ref:
            continue
        cand = (script.parent / ref)
        try:
            cand = cand.resolve()
            cand.relative_to(base.resolve())
        except (OSError, ValueError):
            continue
        if cand.is_file() and cand not in out:
            out.append(cand)
    return out


def _package_token_scripts(root: Path) -> List[str]:
    pkg = root / "package.json"
    if not pkg.is_file():
        return []
    try:
        scripts = (json.loads(_read_text(pkg)) or {}).get("scripts") or {}
    except (ValueError, AttributeError):
        return []
    if not isinstance(scripts, dict):
        return []
    return sorted(k for k, v in scripts.items()
                  if _TOKEN_SCRIPT_KEY_RE.search(k)
                  or "style-dictionary" in str(v) or "token-transformer" in str(v))


def _read_colors(docs: List[Any]) -> Tuple[List[Tuple[str, str]], List[Tuple[str, str]],
                                           List[Tuple[str, str]]]:
    """(colors read as hex, font families, color values that could not be read)."""
    colors: List[Tuple[str, str]] = []
    fonts: List[Tuple[str, str]] = []
    raw: List[Tuple[str, str]] = []
    for doc in docs:
        for name, tok in flatten_dtcg(doc).items():
            typ = str(tok.get("type") or "").lower()
            if typ == "color" or (not typ and normalize_hex(tok["value"])):
                hx = normalize_color(tok["value"])
                if hx:
                    colors.append((name, hx))
                elif isinstance(tok["value"], str):
                    raw.append((name, tok["value"].strip()))
            elif typ in ("fontfamily", "font-family") or "family" in _segments(name):
                fonts.append((name, _first_family(tok["value"])))
    return colors, fonts, raw


def detect_existing_system(root: Any = ".") -> Dict[str, Any]:
    """Find an existing design system under ``root`` and read what it declares.

    Returns ``{"found", "root", "sources", "hints", "declared"}``.

    ``sources`` lists each file or folder of the system as ``{"kind", "path"}``
    (path relative to ``root``), the token source first. Kinds:
    ``tokens-source`` (a token file a build script reads), ``tokens`` (a DTCG
    or tokens JSON file), ``css-foundation``, ``built-output`` (generated
    files under build/, dist/ or out/, or headed "Generated ... Do not
    edit"; never edit these), ``master-md``, ``design-md``, ``build-script``
    and ``system-folder``.

    ``found`` is true only on a strong signal: a token file holding at least
    one color or dimension, a foundation CSS file, or a hand-written MASTER.md
    or DESIGN.md. A file ux-skill wrote and a person then edited is not a
    system: commands write beside it instead of over it. A folder, a build script or a
    package script alone is reported under ``hints`` and is not a system.

    Beyond the conventional folders, a token file is also found by what it
    holds, anywhere in the same bounded walk outside docs, examples and
    tests (the walk counts only stylesheets, pages, templates and JSON and
    locale files toward its cap): a stylesheet (.css, .scss or .pcss) whose
    rules are mostly custom properties on the root or a theme selector (or a
    main stylesheet, such as app.css or globals.css, with a theme block of
    its own), and a DTCG file under any name. A theme selector is the root,
    or a class or attribute that names a theme (.dark, .theme-x,
    data-theme, data-mode); a widget's own class (.dp { --dp-bg }) is a
    component, so a widget stylesheet alone is never a system. Built output
    found that way is left out.

    ``declared`` is read from the token source first, then other token
    files, then built output, then foundation CSS: ``primary`` and
    ``primary_token`` (or ``primary_raw`` and ``primary_note`` when the value
    cannot be read), ``text`` and ``text_token``, ``fonts`` ({display,
    body}, plus ``data`` for a face kept for figures, tables or code, with
    ``data_font_from`` when the code, not a token name, says so), ``colors``
    (every named, non-ramp color in the client's naming, a translucent one
    as #RRGGBBAA), ``languages`` (from the project's pages and templates:
    HTML, Blade, JSX and TSX, Vue, Svelte, Astro, ERB and Twig, by their
    html lang and by Arabic script in their text, most used first, then
    the languages only locale files such as messages/ar.json hold) and
    ``direction`` (rtl when <html> or <body> sets dir="rtl", when a page
    whose text is Arabic does anywhere, or when dir is set from the locale
    and Arabic is one of the languages; a language switcher's dir is not).

    The primary is a color whose name says primary or brand; a name that
    says accent, action, cta or interactive is read only when none does (a
    leading fill word, as in bg-brand, is allowed). A candidate that cannot
    carry a button's text (a near-white tint of the page, or under 4.5:1
    against its own text color and the page) never wins. Of several at one
    rank, the one the code fills buttons and links with most at rest wins:
    hover and focus paints are not counted, and class strings in cva, clsx
    and cn calls are. ``primary_candidates`` lists each with its count and
    ``primary_why`` says which was chosen and why; ``primary_note`` says why
    none was, when no candidate can carry text.

    ``disagreements`` lists each token two sources set to different values:
    any two stylesheets that set it on the root or under one theme (an app
    stylesheet that imports the system's file and sets a token again among
    its component rules undoes the system's value), a token file, and a
    hand-written MASTER.md or DESIGN.md palette. Each names the token (and
    its ``theme``), every file with its value, the file that wins in the
    cascade and why: outside a cascade layer beats inside one, :root beats
    html, and then the file loaded last, by its imports (a package name is
    resolved through node_modules or the workspace packages) or a page's
    links. The winner is "" when these files do not decide it, and an
    import that could not be resolved is said to be so.
    """
    base = Path(root).expanduser()
    result: Dict[str, Any] = {"found": False,
                              "root": str(base.resolve()) if base.exists() else str(base),
                              "sources": [], "hints": [], "declared": {}}
    if not base.is_dir():
        return result
    base = base.resolve()

    sources: List[Dict[str, str]] = []

    def add(kind: str, path: Path) -> None:
        rel = path.relative_to(base).as_posix() if path != base else "."
        if any(s["path"] == rel for s in sources):
            return
        sources.append({"kind": kind, "path": rel})

    # Only the root's own files and the conventional system folders are read,
    # so a repository that merely hosts example systems in docs/ is not one.
    system_dirs: List[str] = list(_SYSTEM_DIRS)
    packages = base / "packages"
    if packages.is_dir():
        for child in sorted(packages.iterdir()):
            rel = "packages/" + child.name
            if child.is_dir() and rel not in system_dirs and any(
                    w in child.name.lower() for w in _PACKAGE_WORDS):
                system_dirs.append(rel)
    seen: set = set()
    files: List[Path] = [p for p in sorted(base.iterdir()) if p.is_file()]
    for rel in system_dirs:
        if (base / rel).is_dir():
            _walk(base / rel, 1, seen, files)
    # The whole project, to the same caps, counting only the files the
    # survey reads, so a folder of images never starves a stylesheet.
    html_files: List[Path] = []
    _walk(base, 0, set(), html_files, _surveyed)

    # Token sources: the .json files a token build script reads.
    scripts = [p for p in files
               if (_BUILD_SCRIPT_RE.match(p.name) and "token" in p.relative_to(base).as_posix().lower())
               or _SD_CONFIG_RE.match(p.name)]
    source_docs: List[Any] = []
    # Each hand-written token file with its document, for the disagreements.
    doc_paths: List[Tuple[Path, Any]] = []
    for script in scripts:
        for src in _script_sources(script, base):
            doc = _token_doc(src)
            if doc is not None:
                source_docs.append(doc)
                doc_paths.append((src, doc))
                add("tokens-source", src)

    token_docs: List[Any] = []
    built_docs: List[Any] = []
    css_files: List[Path] = []
    built_css: List[Path] = []
    for path in files:
        name = path.name
        rel_parts = path.relative_to(base).parts
        if any(s["path"] == path.relative_to(base).as_posix() for s in sources):
            continue
        if _TOKEN_FILE_RE.search(name) or (len(rel_parts) > 1 and name.lower().endswith(".json")):
            doc = _token_doc(path)
            if doc is not None:
                if _is_built(path, base):
                    built_docs.append(doc)
                    add("built-output", path)
                else:
                    token_docs.append(doc)
                    doc_paths.append((path, doc))
                    add("tokens", path)
                continue
        if path in scripts:
            add("build-script", path)
            continue
        if name.lower().endswith(".css"):
            parent_words = {p.lower() for p in rel_parts[:-1]}
            if _FOUNDATION_CSS_RE.search(name) or parent_words & {"foundation", "foundations", "tokens"}:
                if len(css_custom_properties(_read_text(path))) >= 3:
                    if _is_built(path, base):
                        built_css.append(path)
                        add("built-output", path)
                    else:
                        css_files.append(path)
                        add("css-foundation", path)

    # Token sources found by what they hold, anywhere in the walk outside
    # docs, examples and tests: an assets/ folder beside the system, the
    # app's own token stylesheets, the theme block of its main stylesheet
    # and a site's globals, and a DTCG file under any name.
    for path in html_files:
        rel = path.relative_to(base).as_posix()
        low = path.name.lower()
        if any(s["path"] == rel for s in sources) or not survey.in_product(path, base) \
                or low.endswith(".min.css") or _is_built(path, base):
            continue
        if survey.is_style(path):
            if survey.css_token_file(path.name, _read_text(path)):
                css_files.append(path)
                add("css-foundation", path)
        elif low.endswith(".json") and low != "package.json" \
                and '"$value"' in _read_text(path, 400_000):
            doc = _token_doc(path)
            if doc is not None and sum(1 for t in flatten_dtcg(doc).values()
                                       if _is_design_token(t)) >= 3:
                token_docs.append(doc)
                doc_paths.append((path, doc))
                add("tokens", path)

    if _package_token_scripts(base):
        add("build-script", base / "package.json")

    for cand in (base / "MASTER.md", base / "design-system" / "MASTER.md",
                 base / ".ux" / "design-system" / "MASTER.md"):
        if ownership(cand) == "foreign":
            add("master-md", cand)
    for cand in (base / "DESIGN.md", base / "design-system" / "DESIGN.md"):
        if ownership(cand) == "foreign":
            add("design-md", cand)

    for rel in system_dirs:
        d = base / rel
        if (rel in ("design-system", "design-tokens", "tokens") or rel.startswith("packages/")) \
                and d.is_dir() and any(d.iterdir()):
            add("system-folder", d)

    sources.sort(key=lambda s: _KIND_ORDER.get(s["kind"], 9))
    if not any(s["kind"] in _STRONG_KINDS for s in sources):
        result["hints"] = sources
        return result

    # ---- what the system declares: the source first, generated output last
    colors: List[Tuple[str, str]] = []
    font_tokens: List[Tuple[str, str]] = []
    raw_colors: List[Tuple[str, str]] = []
    for tier in (source_docs, token_docs, built_docs):
        if tier:
            colors, font_tokens, raw_colors = _read_colors(tier)
            if colors:
                break

    css_props: Dict[str, str] = {}
    for path in css_files + built_css:
        for k, v in css_custom_properties(_read_text(path)).items():
            css_props.setdefault(k, v)
    css_colors: List[Tuple[str, str]] = []
    css_fonts: List[Tuple[str, str]] = []
    for name, value in css_props.items():
        resolved = resolve_css_var(value, css_props)
        hx = normalize_color(resolved)
        if hx:
            css_colors.append((name.lstrip("-"), hx))
        elif ("font" in name and ("family" in name or "face" in name or name.endswith("font"))) \
                or (_FONT_TOKEN_RE.match(name) and _font_list(resolved)):
            css_fonts.append((name.lstrip("-"), _first_family(resolved, css_props)))

    declared: Dict[str, Any] = {}
    cands = _primary_candidates(colors)
    p_from, pool = "tokens", colors
    if not cands:
        cands = [("--" + n, h, w) for n, h, w in _primary_candidates(css_colors)]
        p_from, pool = "css", css_colors
    if cands:
        named_pool = {"-".join(_segments(n)): h for n, h in pool}
        (p_name, p_hex), why, listed = _choose_primary(cands, html_files, named_pool,
                                                       _canvas(pool))
        if p_hex:
            declared["primary"] = p_hex
            declared["primary_token"] = p_name
            declared["primary_from"] = p_from
            if len(cands) > 1 or cands[0][2] not in _PRIMARY_WORDS:
                declared["primary_why"] = why
        else:
            declared["primary_note"] = why
        if listed:
            declared["primary_candidates"] = listed
    else:
        r_name, r_value = _rank_primary((n, v) for n, v in raw_colors)
        if r_name:
            declared["primary_raw"] = r_value
            declared["primary_token"] = r_name
            declared["primary_note"] = (
                "%s is %s, a color this cannot convert to hex; read it from the system and "
                "pass it as the brand primary by hand." % (r_name, r_value))
    t_name, t_hex = _rank_text(colors, _canvas(colors))
    if not t_hex:
        t_name, t_hex = _rank_text(css_colors, _canvas(css_colors))
        if t_name:
            t_name = "--" + t_name
    if t_hex:
        declared["text"] = t_hex
        declared["text_token"] = t_name
    fonts = _fonts_from(font_tokens) or _fonts_from(css_fonts)
    if "data" not in fonts:
        face, where = survey.data_face(css_files, html_files,
                                       lambda v: _first_family(v, css_props))
        if face and face != fonts.get("body"):
            fonts = {**fonts, "data": face} if fonts else {"display": face, "body": face}
            if fonts.get("body") != face:
                declared["data_font_from"] = where
    if fonts:
        declared["fonts"] = fonts
    named: Dict[str, str] = {}
    for name, hx in (colors or [("--" + n, h) for n, h in css_colors]):
        segs = _segments(name)
        if segs and not segs[-1].isdigit():
            named.setdefault("-".join(segs), hx)
    if named:
        declared["colors"] = named
    langs, rtl = survey.languages(html_files)
    if langs:
        declared["languages"] = langs
    if rtl:
        declared["direction"] = "rtl"
    styles = list(css_files) + [
        p for p in html_files if survey.is_style(p) and p not in css_files
        and survey.in_product(p, base) and not _is_built(p, base)
        and survey.declares(_read_text(p))]
    disagree = survey.disagreements(
        base, styles, doc_paths,
        [base / s["path"] for s in sources if s["kind"] in ("master-md", "design-md")],
        html_files, _reading, flatten_dtcg)
    if disagree:
        declared["disagreements"] = disagree

    result["sources"] = sources
    result["declared"] = declared
    result["found"] = True
    return result


def _surveyed(path: Path) -> bool:
    """A file the survey reads: a stylesheet, a page or template, a JSON
    file (tokens, a package manifest, a locale) or a locale file."""
    return survey.is_style(path) or survey.is_template(path) \
        or path.suffix.lower() == ".json" or bool(survey.locale_of(path))


_FONT_TOKEN_RE = re.compile(r"^--font-(?!size|weight|feature|variation|style|stretch|"
                            r"optical|kerning|smoothing|synthesis)[a-z]", re.I)


def _font_list(value: str) -> bool:
    """True when a value reads as a font list, the var() members it may
    open with left aside."""
    from engine.io.values_in import NotRead, read_value, split_top  # engine.io imports this
    parts = split_top(value, ",")
    while parts and parts[0].strip().startswith("var("):
        parts = parts[1:]
    try:
        return bool(parts) and read_value(", ".join(parts))[0] == "fontFamily"
    except NotRead:
        return False


def _reading(value: str, props: Dict[str, str]) -> str:
    """What a value reads as, for telling two values from two spellings of one."""
    resolved = resolve_css_var(value, props)
    return normalize_color(resolved) or " ".join(resolved.split()).lower()


def mark_suggestions(payload: Dict[str, Any], found: Optional[Dict[str, Any]]) -> Dict[str, Any]:
    """``payload`` (an engine result) marked as suggestions when ``found`` is
    an existing system: ``status: suggestion`` plus the ``existing_system``
    block, so no caller mistakes the engine's picks for the project's own."""
    if not found or not found.get("found"):
        return payload
    return {**payload, "status": "suggestion",
            "existing_system": {"root": found.get("root", ""),
                                "sources": list(found.get("sources") or []),
                                "declared": dict(found.get("declared") or {})}}


def client_files_in(out_dir: Any, files: Any) -> List[str]:
    """Of the files a ux-skill build would write into ``out_dir`` (a mapping
    of name to text, or names), the ones that already exist there with other
    content, when ``out_dir`` holds a client's design system (what
    ``detect_existing_system`` finds). A folder whose tokens.json carries
    ux-skill's own extension key is ux-skill's, and a folder that is not a
    system holds no client files."""
    out = Path(out_dir)
    tokens = out / "tokens.json"
    if tokens.is_file() and "io.github.laith0003.ux-skill" in _read_text(tokens):
        return []
    if not out.is_dir() or not detect_existing_system(out).get("found"):
        return []
    theirs = []
    for name in files:
        path = out / name
        if not path.is_file():
            continue
        if hasattr(files, "keys") and _read_text(path) == files[name]:
            continue
        theirs.append(name)
    return sorted(theirs)
