def _num(text: str, percent_scale: float = 1.0) -> float:
    """A CSS number; a percentage is scaled so 100% equals ``percent_scale``."""
    t = text.strip().lower()
    if t in ("none", ""):
        return 0.0
    if t.endswith("%"):
        return float(t[:-1]) / 100.0 * percent_scale
    return float(t)


def _hue(text: str) -> float:
    """A hue in degrees, read by the importers' value reader (a number, or
    an angle in deg, turn, rad or grad). Raises ValueError otherwise."""
    from engine.io.values_in import NotRead, hue_degrees  # engine.io imports this package
    t = text.strip()
    if not t:
        return 0.0
    try:
        return hue_degrees(t)
    except NotRead as exc:
        raise ValueError(str(exc)) from None


def _rgb_hex(r: float, g: float, b: float) -> str:
    return "#%02X%02X%02X" % tuple(max(0, min(255, int(round(c)))) for c in (r, g, b))


def _oklch_hex(L: float, C: float, H: float) -> str:
    # CSS Color 4 gamut mapping, the same the importers' value reader uses.
    from engine.foundations.color_math import gamut_map_oklch
    return gamut_map_oklch(L, C, H)[0]


def _from_hsl(h: float, s: float, light: float) -> str:
    """An hsl color (saturation and lightness from 0 to 1, clamped) as hex,
    converted by the importers' value reader."""
    from engine.io.values_in import hsl_to_rgb  # engine.io imports this package
    return _rgb_hex(*hsl_to_rgb(h, max(0.0, min(1.0, s)), max(0.0, min(1.0, light))))


def _function_hex(name: str, args: str) -> str:
    parts = [p for p in re.split(r"[\s,/]+", args.strip()) if p]
    try:
        if name in ("rgb", "rgba") and len(parts) >= 3:
            return _rgb_hex(*(_num(p, 255.0) for p in parts[:3]))
        if name in ("hsl", "hsla") and len(parts) >= 3:
            return _from_hsl(_hue(parts[0]), _num(parts[1], 1.0) if parts[1].endswith("%")
                             else float(parts[1]) / 100.0,
                             _num(parts[2], 1.0) if parts[2].endswith("%")
                             else float(parts[2]) / 100.0)
        if name == "oklch" and len(parts) >= 3:
            return _oklch_hex(_num(parts[0], 1.0), _num(parts[1], 0.4), _hue(parts[2]))
        if name == "oklab" and len(parts) >= 3:
            L, a, b = _num(parts[0], 1.0), _num(parts[1], 0.4), _num(parts[2], 0.4)
            return _oklch_hex(*oklab_to_oklch(L, a, b))
        if name == "color" and len(parts) >= 4 and parts[0].lower() == "srgb":
            return _rgb_hex(*(_num(p, 1.0) * 255 for p in parts[1:4]))
    except (ValueError, ImportError):
        return ""
    return ""


def normalize_hex(value: Any) -> str:
    """A color as #RRGGBB upper case, or "" when it is not a color this can
    read. Reads hex, rgb(), hsl(), oklch(), oklab(), color(srgb ...) and the
    DTCG color object (hex, or components in srgb, hsl, oklch or oklab)."""
    return normalize_color(value)[:7]


def _alpha_suffix(alpha: Any) -> str:
    """The AA of #RRGGBBAA for an alpha from 0 to 1 (or a percentage), or ""
    when it is opaque or not a number."""
    try:
        a = _num(str(alpha), 1.0)
    except ValueError:
        return ""
    a = max(0.0, min(1.0, a))
    return "" if a >= 1 else "%02X" % round(a * 255)


def normalize_color(value: Any) -> str:
    """A color as #RRGGBB, or #RRGGBBAA when it is translucent (an rgba()
    keeps its alpha), upper case; "" when it is not a color this can read."""
    if isinstance(value, dict):
        hx = _normalize_opaque(value)
        return hx + _alpha_suffix(value.get("alpha", 1)) if hx else ""
    if not isinstance(value, str):
        return ""
    s = value.strip()
    m = _FUNC_RE.match(s)
    if not (m or _HEX_RE.match(s)):
        return ""
    # The importers' value reader first, so detect and import read one color
    # the same way. What it refuses by design (color(srgb), loose syntax)
    # detect still reads leniently, to find a primary.
    from engine.io.values_in import NotRead, read_value  # engine.io imports this package
    try:
        kind, hx = read_value(s)
        if kind == "color":
            return hx
    except NotRead:
        pass
    if not m:
        return ""
    hx = _function_hex(m.group(1).lower(), m.group(2))
    if not hx:
        return ""
    parts = [p for p in re.split(r"[\s,/]+", m.group(2).strip()) if p]
    at = 4 if m.group(1).lower() == "color" else 3
    return hx + (_alpha_suffix(parts[at]) if len(parts) > at else "")


def _normalize_opaque(value: Any) -> str:
    """A DTCG color object as #RRGGBB: its hex, or its components in srgb,
    hsl, oklch or oklab."""
    hx = value.get("hex")
    if isinstance(hx, str):
        return normalize_hex(hx)
    comps = value.get("components")
    space = str(value.get("colorSpace") or "srgb").lower()
    if isinstance(comps, list) and len(comps) >= 3:
        try:
            c = [0.0 if x in (None, "none") else float(x) for x in comps[:3]]
        except (TypeError, ValueError):
            return ""
        try:
            if space == "srgb":
                return _rgb_hex(*(x * 255 for x in c))
            if space == "hsl":
                return _from_hsl(c[0], c[1] / 100.0, c[2] / 100.0)
            if space == "oklch":
                return _oklch_hex(*c)
            if space == "oklab":
                return _oklch_hex(*oklab_to_oklch(*c))
        except (ValueError, ImportError):
            return ""
    return ""


def _segments(path: str) -> List[str]:
    return [s for s in re.split(r"[.\-_/\s]+", path.lower()) if s]


def _read_text(path: Path, limit: int = 2_000_000) -> str:
    try:
        data = path.read_bytes()[:limit]
    except OSError:
        return ""
    return data.decode("utf-8", errors="ignore")


def _parse_frontmatter(text: str) -> Tuple[Dict[str, str], str]:
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return {}, text
    meta: Dict[str, str] = {}
    for idx, line in enumerate(lines[1:], start=1):
        if line.strip() == "---":
            return meta, "\n".join(lines[idx + 1:])
        m = re.match(r"^([A-Za-z0-9_]+)\s*:\s*(.*)$", line)
        if m:
            meta[m.group(1)] = m.group(2).strip().strip('"').strip("'")
    return {}, text


