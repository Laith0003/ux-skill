def text_digest(text: str) -> str:
    """The sha256 of ``text`` without its digest line."""
    return hashlib.sha256(_DIGEST_LINE_RE.sub("", text).encode("utf-8")).hexdigest()


def stamp_digest(text: str, comment: bool = False, css: bool = False) -> str:
    """``text`` with a digest line added after its opening ``---``: a
    frontmatter key, or a YAML comment when ``comment`` is True (for a
    DESIGN.md, whose frontmatter keys are a fixed standard). With ``css``
    the line goes inside a block comment that opens the stylesheet: the
    first one when the text opens with ``/*`` on a line of its own, else a
    comment of its own."""
    if css:
        bare = text if text.startswith("/*\n") else "/*\n*/\n" + text
        return "/*\n" + "ux-skill-digest: %s\n" % text_digest(bare) + bare[3:]
    digest = text_digest(text)
    line = ("# ux-skill-digest: %s\n" if comment else DIGEST_KEY + ": %s\n") % digest
    if text.startswith("---\n"):
        return "---\n" + line + text[4:]
    return line + text


def is_ux_skill_text(text: str) -> bool:
    """True when ``text`` carries ux-skill's digest and still matches it:
    what ``is_ux_skill_file`` says of a file, for text already read."""
    m = _DIGEST_LINE_RE.search(text)
    return bool(m) and m.group(1) == text_digest(text)


def ownership(path: Any) -> str:
    """Who a file belongs to: ``missing``; ``owned`` (ux-skill wrote it and
    it is unchanged); ``edited`` (ux-skill wrote it, then a person changed
    it); ``legacy`` (the exact shape ux-skill wrote before the digest
    existed); ``foreign`` (anything else, such as a hand-written file)."""
    p = Path(path)
    if not p.is_file():
        return "missing"
    text = _read_text(p)
    m = _DIGEST_LINE_RE.search(text)
    if m:
        return "owned" if m.group(1) == text_digest(text) else "edited"
    meta, body = _parse_frontmatter(text)
    first = next((ln for ln in body.splitlines() if ln.strip()), "").strip()
    if set(meta) in _LEGACY_KEY_SETS and (first == _LEGACY_MASTER_HEADING
                                         or first.startswith("# Page \u2014 ")):
        return "legacy"
    if p.suffix.lower() == ".md" and DESIGN_MD_MARKER in text and text.startswith("---"):
        return "legacy"
    return "foreign"


def is_ux_skill_file(path: Any) -> bool:
    """True only while ux-skill's own digest still matches the file: a file
    it wrote and nobody has changed since. Safe to overwrite."""
    return ownership(path) == "owned"


